"""Fix tests ACC-073 to ACC-120. Recomputes section boundaries before each fix."""
import re

APP_PATH = '/Users/michaellascar/Projects/mixel-test/apps.json'

def S(*steps):
    return '\\n'.join(s.replace('"', '\\"') for s in steps)

def replace_test(text, test_id, start, end, new_steps, new_expected):
    area = text[start:end]
    idx = area.find(f'"id": "{test_id}"')
    if idx == -1:
        return text, False
    next_id = area.find('"id": "', idx + 15)
    if next_id == -1: next_id = len(area)
    block = area[idx:next_id]
    block = re.sub(r'"steps":\s*"(?:[^"\\]|\\.)*"', f'"steps": "{new_steps}"', block, flags=re.DOTALL)
    block = re.sub(r'"expected":\s*"(?:[^"\\]|\\.)*"', f'"expected": "{new_expected}"', block, flags=re.DOTALL)
    new_area = area[:idx] + block + area[next_id:]
    return text[:start] + new_area + text[end:], True

with open(APP_PATH, 'r') as f:
    content = f.read()

def fix(tid, de_s=None, de_e=None, fr_s=None, fr_e=None, en_s=None, en_e=None, it_s=None, it_e=None):
    global content
    # Recompute boundaries fresh each time to avoid drift
    de0 = content.find('  DE: [')
    fr0 = content.find('  FR: [')
    en0 = content.find('  EN: [')
    it0 = content.find('  IT: [')
    results = []
    if de_s is not None:
        content, ok = replace_test(content, tid, de0, fr0, de_s, de_e)
        results.append(f'DE:{"OK" if ok else "MISS"}')
    if fr_s is not None:
        # Recompute after DE change
        fr0 = content.find('  FR: [')
        en0 = content.find('  EN: [')
        content, ok = replace_test(content, tid, fr0, en0, fr_s, fr_e)
        results.append(f'FR:{"OK" if ok else "MISS"}')
    if en_s is not None:
        en0 = content.find('  EN: [')
        it0 = content.find('  IT: [')
        content, ok = replace_test(content, tid, en0, it0, en_s, en_e)
        results.append(f'EN:{"OK" if ok else "MISS"}')
    if it_s is not None:
        it0 = content.find('  IT: [')
        content, ok = replace_test(content, tid, it0, len(content), it_s, it_e)
        results.append(f'IT:{"OK" if ok else "MISS"}')
    print(f'{tid}: {" ".join(results)}')

